#!/usr/bin/env node
/**
 * Generate website/docs/pages-index.md — a full markdown list of every
 * docs page under website/docs/.
 *
 * Usage: node ./scripts/generate-docs-index.mjs
 */
import fs from 'node:fs';
import path from 'node:path';
import {fileURLToPath} from 'node:url';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const websiteRoot = path.resolve(__dirname, '..');
const docsRoot = path.join(websiteRoot, 'docs');
const outputPath = path.join(docsRoot, 'pages-index.md');

const SECTION_LABELS = {
  '': 'Start here',
  tools: 'Tools & Platforms',
  strategy: 'Strategy & Growth',
  guides: 'Guides & Articles',
  development: 'Development',
  operations: 'Operations & Metrics',
  more: 'More',
};

const SECTION_ORDER = [
  '',
  'tools',
  'strategy',
  'guides',
  'development',
  'operations',
  'more',
];

function walkDocs(dir, out = []) {
  for (const entry of fs.readdirSync(dir, {withFileTypes: true})) {
    if (entry.name.startsWith('_') || entry.name.startsWith('.')) {
      continue;
    }
    const full = path.join(dir, entry.name);
    if (entry.isDirectory()) {
      walkDocs(full, out);
      continue;
    }
    if (entry.name.endsWith('.md') || entry.name.endsWith('.mdx')) {
      out.push(full);
    }
  }
  return out;
}

function parseFrontmatter(text) {
  if (!text.startsWith('---')) {
    return {};
  }
  const end = text.indexOf('\n---', 3);
  if (end === -1) {
    return {};
  }
  const block = text.slice(4, end);
  const data = {};
  for (const line of block.split('\n')) {
    const match = line.match(/^([A-Za-z0-9_]+):\s*(.*)$/);
    if (!match) {
      continue;
    }
    let value = match[2].trim();
    if (
      (value.startsWith('"') && value.endsWith('"')) ||
      (value.startsWith("'") && value.endsWith("'"))
    ) {
      value = value.slice(1, -1);
    }
    data[match[1]] = value;
  }
  return data;
}

function toDocId(relPath) {
  return relPath.replace(/\.(md|mdx)$/i, '').replace(/\\/g, '/');
}

function toSitePath(docId) {
  if (docId === 'intro') {
    return '/docs/';
  }
  if (docId.endsWith('/index')) {
    return `/docs/${docId.slice(0, -'/index'.length)}/`;
  }
  return `/docs/${docId}`;
}

function relativeLinkFromIndex(relPath) {
  // pages-index.md lives at docs/pages-index.md
  return `./${relPath.replace(/\\/g, '/')}`;
}

function sectionKey(relPath) {
  const parts = relPath.split(/[\\/]/);
  return parts.length > 1 ? parts[0] : '';
}

function collectPages() {
  const files = walkDocs(docsRoot);
  const pages = [];

  for (const file of files) {
    const relPath = path.relative(docsRoot, file);
    const text = fs.readFileSync(file, 'utf8');
    const fm = parseFrontmatter(text);
    const docId = toDocId(relPath);
    const title = fm.title || fm.sidebar_label || docId;
    const description = fm.description || '';
    const sidebarLabel = fm.sidebar_label || title;

    pages.push({
      relPath: relPath.replace(/\\/g, '/'),
      docId,
      title,
      sidebarLabel,
      description,
      sitePath: toSitePath(docId),
      section: sectionKey(relPath),
      draft: fm.draft === 'true',
      unlisted: fm.unlisted === 'true',
    });
  }

  pages.sort((a, b) => {
    const ai = SECTION_ORDER.indexOf(a.section);
    const bi = SECTION_ORDER.indexOf(b.section);
    const aOrder = ai === -1 ? 999 : ai;
    const bOrder = bi === -1 ? 999 : bi;
    if (aOrder !== bOrder) {
      return aOrder - bOrder;
    }
    return a.relPath.localeCompare(b.relPath);
  });

  return pages;
}

function renderMarkdown(pages) {
  const lines = [
    '---',
    'title: "All Docs Pages"',
    'description: "Auto-generated full list of every documentation page in this site (markdown sources under website/docs)."',
    'keywords:',
    '  - docs index',
    '  - all pages',
    '  - sitemap',
    '  - markdown',
    'sidebar_label: "All Docs Pages"',
    'sidebar_position: 5',
    'image: img/docusaurus-social-card.jpg',
    'hide_title: false',
    'hide_table_of_contents: false',
    'toc_min_heading_level: 2',
    'toc_max_heading_level: 3',
    'draft: false',
    'unlisted: false',
    'category: meta',
    'topics:',
    '  - meta',
    'audience:',
    '  - contributors',
    'seo:',
    '  title: "All Docs Pages | Awesome Email Marketing"',
    '  description: "Auto-generated full list of every documentation page in this site."',
    '  robots: index,follow',
    '  canonical_path: "/docs/pages-index"',
    '  og_type: article',
    '  twitter_card: summary_large_image',
    '---',
    '',
    '# All Docs Pages',
    '',
    `Auto-generated list of every markdown/MDX page under \`website/docs/\` (${pages.length} pages).`,
    '',
    '**Do not edit this file by hand.** Run `npm run generate:docs-index` in `website/`, or wait for the **Update docs pages index** GitHub Action after docs changes land on `main`.',
    '',
  ];

  let currentSection = null;
  for (const page of pages) {
    if (page.section !== currentSection) {
      currentSection = page.section;
      const label = SECTION_LABELS[currentSection] || currentSection || 'Other';
      lines.push('', `## ${label}`, '');
    }

    const flags = [];
    if (page.draft) {
      flags.push('draft');
    }
    if (page.unlisted) {
      flags.push('unlisted');
    }
    const flagText = flags.length ? ` _( ${flags.join(', ')} )_` : '';
    const desc = page.description ? ` — ${page.description}` : '';

    lines.push(
      `- [${page.title}](${relativeLinkFromIndex(page.relPath)}) (\`${page.relPath}\`) → [\`${page.sitePath}\`](${page.sitePath})${flagText}${desc}`,
    );
  }

  lines.push(
    '',
    '## Flat checklist',
    '',
    'Copy-friendly path list:',
    '',
    '```text',
  );
  for (const page of pages) {
    lines.push(page.relPath);
  }
  lines.push('```', '');

  return `${lines.join('\n')}\n`;
}

const pages = collectPages();
const markdown = renderMarkdown(pages);
fs.writeFileSync(outputPath, markdown, 'utf8');

const jsonPath = path.join(websiteRoot, 'static/api/v1/docs-pages.json');
fs.mkdirSync(path.dirname(jsonPath), {recursive: true});
fs.writeFileSync(
  jsonPath,
  `${JSON.stringify(
    {
      generatedAt: new Date().toISOString(),
      count: pages.length,
      pages: pages.map((page) => ({
        id: page.docId,
        title: page.title,
        sidebarLabel: page.sidebarLabel,
        description: page.description,
        path: page.relPath,
        url: page.sitePath,
        section: page.section || 'root',
        draft: page.draft,
        unlisted: page.unlisted,
      })),
    },
    null,
    2,
  )}\n`,
  'utf8',
);

console.log(
  `Wrote ${pages.length} pages to ${path.relative(websiteRoot, outputPath)} and ${path.relative(websiteRoot, jsonPath)}`,
);
